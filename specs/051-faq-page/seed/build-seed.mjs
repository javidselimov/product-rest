#!/usr/bin/env node
// Spec 051, T011: faq-az.json + topic-names-en.json (+ faq-en.json when it exists) → 0033-faq-seed.sql.
//
//   node build-seed.mjs
//
// The SQL runs once: everything sits in one DO block that returns when faq_topics already has rows, so an editor's
// work is never overwritten. Pages are found by slug, never by id (ids differ between environments).
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(HERE, '../../../product-rest/api-cbar-admin/db/migrations/0033-faq-seed.sql')
const TAG = '$faq$'
// The FAQ page's legacy az title and the Figma one; the title changes only while it is still the legacy one.
const LEGACY_TITLE = 'Sual − cavab'
const FIGMA_TITLE = 'Sual-cavab'
// Topic → CMS page (az slug) that shows its link card. Only pages that exist get the link.
const TOPIC_PAGES = { 'pul-siyaseti': ['pul-siyaseti'] }

const read = (name) => JSON.parse(readFileSync(join(HERE, name), 'utf8'))
const az = read('faq-az.json')
const enNames = read('topic-names-en.json')
const en = existsSync(join(HERE, 'faq-en.json')) ? read('faq-en.json') : null

function lit(text) {
  if (text.includes(TAG)) throw new Error(`text contains ${TAG}`)
  return `${TAG}${text}${TAG}`
}
const str = (text) => `'${text.replaceAll("'", "''")}'`

const lines = []
const push = (s = '') => lines.push(s)

push('-- FAQ "Sual-cavab" content (spec 051), generated by specs/051-faq-page/seed/build-seed.mjs from the legacy CMS page')
push('-- `sual-cavab` (test API, 2026-11-17). Do not edit by hand: change the generator and ship a new migration.')
push(`-- ${az.topics.length} topics, ${az.topics.reduce((n, t) => n + t.questions.length, 0)} questions (az), ${az.videos.length} video(s).`)
push('-- en: topic names only; question/answer translation is deferred (spec 051 decision 3), so en shows no topic yet.')
push('-- Runs once: returns when faq_topics has rows. The legacy "Playlist" link is not migrated (spec 051 clarify).')
push('DO $faqseed$')
push('DECLARE')
push('    t_id integer;')
push('    q_id integer;')
push('    v_id integer;')
push('BEGIN')
push('    IF EXISTS (SELECT FROM faq_topics) THEN')
push("        RAISE NOTICE 'spec 051: faq_topics is not empty, FAQ seed skipped';")
push('        RETURN;')
push('    END IF;')

az.topics.forEach((topic, ti) => {
  const enName = enNames[topic.slug]
  if (!enName) throw new Error(`no en name for ${topic.slug}`)
  const enTopic = en?.topics[ti]
  push()
  push(`    -- ${topic.name} (${topic.questions.length})`)
  push(`    INSERT INTO faq_topics (slug, sort_order, status) VALUES (${str(topic.slug)}, ${ti + 1}, 'published') RETURNING id INTO t_id;`)
  push(`    INSERT INTO faq_topic_translations (topic_id, locale, name) VALUES (t_id, 'az', ${str(topic.name)}), (t_id, 'en', ${str(enName)});`)
  topic.questions.forEach((q, qi) => {
    push(`    INSERT INTO faq_questions (topic_id, sort_order, status) VALUES (t_id, ${qi + 1}, 'published') RETURNING id INTO q_id;`)
    const rows = [`(q_id, 'az', ${lit(q.question)}, ${lit(q.answer)})`]
    const enQ = enTopic?.questions[qi]
    if (enQ?.question?.trim() && enQ?.answer?.trim()) rows.push(`(q_id, 'en', ${lit(enQ.question)}, ${lit(enQ.answer)})`)
    push(`    INSERT INTO faq_question_translations (question_id, locale, question, answer) VALUES ${rows.join(', ')};`)
  })
  for (const pageSlug of TOPIC_PAGES[topic.slug] ?? []) {
    push(`    INSERT INTO faq_topic_pages (topic_id, page_id, sort_order)`)
    push(`    SELECT t_id, pt.page_id, 0 FROM page_translations pt JOIN pages p ON p.id = pt.page_id`)
    push(`    WHERE pt.locale = 'az' AND pt.slug = ${str(pageSlug)} AND p.deleted_at IS NULL ON CONFLICT DO NOTHING;`)
  }
})

az.videos.forEach((video, vi) => {
  push()
  push(`    INSERT INTO faq_videos (youtube_url, sort_order, status) VALUES (${str(video.url)}, ${vi + 1}, 'published') RETURNING id INTO v_id;`)
  push(`    INSERT INTO faq_video_translations (video_id, locale, title) VALUES (v_id, 'az', ${str(video.title)});`)
})

push()
push("    -- The FAQ page's title as in Figma, only while it is still the legacy one (an editor's title is kept).")
push("    IF has_table_privilege('page_translations', 'UPDATE') THEN")
push(`        UPDATE page_translations SET title = ${str(FIGMA_TITLE)}`)
push(`        WHERE locale = 'az' AND slug = 'sual-cavab' AND title = ${str(LEGACY_TITLE)};`)
push('    ELSE')
push("        RAISE WARNING 'spec 051: no UPDATE on page_translations, FAQ page title left as is';")
push('    END IF;')
push('END $faqseed$;')

writeFileSync(OUT, `${lines.join('\n')}\n`, 'utf8')
console.log(`written ${OUT} (${lines.length} lines)`)
