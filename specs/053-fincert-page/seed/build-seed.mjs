#!/usr/bin/env node
// Spec 053, T049: writes api-cbar-admin/db/migrations/0037-fincert-seed.sql from fincert-az.json, fincert-en.json
// (extract.mjs) and fincert-first.json. Deterministic: the same input gives the same bytes (no dates, stable order).
//
//   node build-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(HERE, '../../../product-rest/api-cbar-admin/db/migrations/0037-fincert-seed.sql')
const TAG = '$fincert$'
const LOCALES = ['az', 'en']

const read = (name) => JSON.parse(readFileSync(join(HERE, name), 'utf8'))
const data = { az: read('fincert-az.json'), en: read('fincert-en.json') }
const first = read('fincert-first.json')

/** A dollar-quoted literal; refuses text that would end the quote early. */
function lit(value) {
  if (value === null || value === undefined) return 'NULL'
  const text = String(value)
  if (text.includes(TAG)) throw new Error(`text contains ${TAG}: ${text.slice(0, 60)}`)
  return `${TAG}${text}${TAG}`
}

for (const field of ['email', 'phone']) {
  if (data.az[field] !== data.en[field]) throw new Error(`${field} differs between az and en`)
}
if (data.az.portal.url !== data.en.portal.url) throw new Error('portal url differs between az and en')
if (data.az.directions.length !== data.en.directions.length) throw new Error('direction counts differ between az and en')

const lines = []
const out = (line = '') => lines.push(line)

out('-- FinCERT content (spec 053), generated by specs/053-fincert-page/seed/build-seed.mjs from the legacy CMS page')
out('-- `fincert` (page 133, test API). Do not edit by hand: change the generator and ship a new migration.')
out(`-- ${data.az.directions.length} directions (az + en), 1 membership (FIRST: az from Figma, en a draft to check), contacts, portal, RFC-2350.`)
out('--')
out('-- RFC-2350: the legacy file is a link to uploads.cbar.az and is not in the media library of the test environment')
out('-- (research R10). A media file with the legacy file name is used when one exists; otherwise the legacy link is kept')
out('-- in rfc_url, so the section does not disappear on deploy day. An editor who uploads the document replaces it.')
out('-- The FIRST logo is uploaded from the panel. Page texts are not touched: page 133 stays the fallback (FR-016).')
out('--')
out('-- Runs once: only while a non-deleted page with the az slug `fincert` exists and the three FinCERT tables are empty')
out('-- (deleted rows included), so a second run, or a run after an editor deleted a row, creates nothing.')
out('-- "FinCERT (Kopya)" (`fincert-copy`, page 479) leaves the left menus (spec 041/048).')
out('DO $fincertseed$')
out('DECLARE')
out('    d_id integer;')
out('    m_id integer;')
for (const locale of LOCALES) out(`    rfc_${locale} bigint;`)
out('BEGIN')
out('    IF NOT EXISTS (')
out('        SELECT FROM pages p JOIN page_translations t ON t.page_id = p.id')
out("        WHERE t.locale = 'az' AND t.slug = 'fincert' AND p.deleted_at IS NULL")
out('    ) THEN')
out("        RAISE NOTICE 'spec 053: page fincert not found, FinCERT seed skipped';")
out('        RETURN;')
out('    END IF;')
out('    IF EXISTS (SELECT FROM fincert_settings) OR EXISTS (SELECT FROM fincert_directions)')
out('       OR EXISTS (SELECT FROM fincert_memberships) THEN')
out("        RAISE NOTICE 'spec 053: FinCERT tables are not empty, FinCERT seed skipped';")
out('        RETURN;')
out('    END IF;')
out()
for (const locale of LOCALES) {
  out(`    SELECT id INTO rfc_${locale} FROM media_assets`)
  out(`    WHERE original_name = ${lit(data[locale].rfc.legacyName)} AND deleted_at IS NULL ORDER BY id LIMIT 1;`)
}
out()
out('    INSERT INTO fincert_settings (id, email, phone, portal_url)')
out(`    VALUES (1, ${lit(data.az.email)}, ${lit(data.az.phone)}, ${lit(data.az.portal.url)});`)
out('    INSERT INTO fincert_setting_translations')
out('        (settings_id, locale, mission, portal_title, portal_description, rfc_media_id, rfc_url) VALUES')
LOCALES.forEach((locale, i) => {
  const d = data[locale]
  const sep = i === LOCALES.length - 1 ? ';' : ','
  out(
    `        (1, '${locale}', ${lit(d.mission)}, ${lit(d.portal.title)}, ${lit(d.portal.description)}, rfc_${locale}, ` +
      `CASE WHEN rfc_${locale} IS NULL THEN ${lit(d.rfc.url)} END)${sep}`,
  )
})
out()
data.az.directions.forEach((direction, i) => {
  out(`    -- ${i + 1}. ${direction.title}`)
  out(`    INSERT INTO fincert_directions (sort_order, status) VALUES (${i + 1}, 'published') RETURNING id INTO d_id;`)
  out('    INSERT INTO fincert_direction_translations (direction_id, locale, title, body) VALUES')
  LOCALES.forEach((locale, j) => {
    const d = data[locale].directions[i]
    out(`        (d_id, '${locale}', ${lit(d.title)}, ${lit(d.body)})${j === LOCALES.length - 1 ? ';' : ','}`)
  })
})
out()
out(`    INSERT INTO fincert_memberships (url, sort_order, status) VALUES (${lit(first.url)}, 1, 'published') RETURNING id INTO m_id;`)
out('    INSERT INTO fincert_membership_translations (membership_id, locale, name, description, badge) VALUES')
LOCALES.forEach((locale, j) => {
  const t = first.translations[locale]
  out(`        (m_id, '${locale}', ${lit(t.name)}, ${lit(t.description)}, ${lit(t.badge)})${j === LOCALES.length - 1 ? ';' : ','}`)
})
out()
out('    -- In shared environments page_details may belong to another role (see 0028).')
out("    IF has_table_privilege('page_details', 'INSERT') AND has_table_privilege('page_details', 'UPDATE') THEN")
out('        INSERT INTO page_details (page_id, show_in_side_nav)')
out('        SELECT t.page_id, false FROM page_translations t')
out("        WHERE t.locale = 'az' AND t.slug = 'fincert-copy'")
out('        ON CONFLICT (page_id) DO UPDATE SET show_in_side_nav = false;')
out('    ELSE')
out("        RAISE WARNING 'spec 053: no INSERT/UPDATE on page_details, fincert-copy stays in the menus';")
out('    END IF;')
out()
out(`    RAISE NOTICE 'spec 053: fincert seeded (directions ${data.az.directions.length}, memberships 1, rfc az=% en=%)',`)
out("        CASE WHEN rfc_az IS NULL THEN 'url' ELSE 'media' END, CASE WHEN rfc_en IS NULL THEN 'url' ELSE 'media' END;")
out('END')
out('$fincertseed$;')

writeFileSync(OUT, `${lines.join('\n')}\n`)
console.log(`wrote ${OUT} (${lines.length} lines)`)
