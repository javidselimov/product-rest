// Spec 054 T068: tree.json → api-cbar-admin/db/migrations/0041-publications-tree-seed.sql (research R13). Deterministic:
// building twice gives the same bytes.
//
//   node specs/054-publications-research/seed/build-tree-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const here = new URL('.', import.meta.url)
const t = JSON.parse(readFileSync(new URL('tree.json', here), 'utf8'))
const out = new URL('../../../product-rest/api-cbar-admin/db/migrations/0041-publications-tree-seed.sql', here)

const q = (s) => `'${String(s).replace(/'/g, "''")}'`
/** Dollar quoting for HTML, with a tag that never occurs in the text. */
const html = (s) => {
  if (s.includes('$html$')) throw new Error('unexpected $html$ in text')
  return `$html$${s}$html$`
}
const escapeHtml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const paragraphs = (list) => list.map((p) => `<p>${escapeHtml(p)}</p>`).join('')
const array = (list) => `ARRAY[${list.map(q).join(', ')}]`

const groupRows = t.groups
  .map((g, i) =>
    `        (${i + 1}, ${q(g.slug.az)}, ${q(g.slug.en)}, ${q(g.title.az)}, ${q(g.title.en)},\n         ${html(paragraphs(g.intro.az))},\n         ${html(paragraphs(g.intro.en))},\n         ${array(g.children)})`,
  )
  .join(',\n')

const titleRows = t.titles
  .flatMap((title) =>
    ['az', 'en'].filter((l) => title[l]).map((l) => `        (${q(title.slug)}, ${q(l)}, ${q(title[l].legacy)}, ${q(title[l].figma)})`),
  )
  .join(',\n')

const introRows = t.intros
  .flatMap((intro) =>
    Object.entries(intro.locales).map(
      ([l, v]) => `        (${q(intro.slug)}, ${q(l)}, ${q(v.legacyMd5)}, ${html(paragraphs([v.intro]))})`,
    ),
  )
  .join(',\n')

const groupLabelRows = t.menuGroups
  .flatMap((g) => g.slugs.flatMap((slug) => ['az', 'en'].map((l) => `        (${q(slug)}, ${q(l)}, ${q(g.group[l])})`)))
  .join(',\n')

const sql = `-- Publications and research (spec 054, research R13): the section tree as in Figma (\`2698:5000\`). Generated by
-- specs/054-publications-research/seed/build-tree-seed.mjs from tree.json — edit those, not this file.
--
-- 1. Two group pages under the root, "Tədqiqatlar" and "Nəşrlər, hesabatlar və sənədlər", created only while missing.
-- 2. The Figma pages move under them in the Figma order, "Rəqəmsal fırıldaqçılıq statistikası" and "Ödəniş xidmətləri"
--    from the consumer rights section; a page moves only while it is still under its legacy parent, and its menu flags
--    are set only then, so an editor's later change stands. Addresses are slugs, so none changes; nothing is deleted.
-- 3. "Ödəniş xidmətləri" is listed only in the dropdown menus (page_nav_details, 0039).
-- 4. The six legacy pages Figma leaves out stay under the root and leave every menu; so does the draft root.
-- 5. Menu group labels (page_translation_details, shown from spec 055), only where a page has none.
-- 6. Figma titles, only over the legacy titles; Figma intros, only over the legacy texts (md5).
-- Pages are found by az slug: ids differ between environments. The "(Kopya)" draft tree keeps its pages and texts; only
-- its root leaves the menus (4), as the consumer section's draft did in 0031.
DO $seed$
DECLARE
    root_id      integer;
    root_path    ltree;
    consumer_id  integer;
    g            record;
    group_id     integer;
    group_path   ltree;
    group_slug   text;
    child_slug   text;
    child_id     integer;
    child_parent integer;
    child_path   ltree;
    new_path     ltree;
    seq          integer;
    created      integer := 0;
    moved        integer := 0;
    changed      integer;
BEGIN
    -- In shared environments the tables may belong to another role (see 0028, 0030, 0031).
    IF NOT has_table_privilege('pages', 'INSERT')
       OR NOT has_table_privilege('pages', 'UPDATE')
       OR NOT has_table_privilege('page_translations', 'INSERT')
       OR NOT has_table_privilege('page_translations', 'UPDATE')
       OR NOT has_table_privilege('page_details', 'INSERT')
       OR NOT has_table_privilege('page_details', 'UPDATE')
       OR NOT has_table_privilege('page_nav_details', 'INSERT')
       OR NOT has_table_privilege('page_translation_details', 'INSERT') THEN
        RAISE WARNING 'spec 054: missing INSERT/UPDATE privileges on the page tables, publications tree seed skipped';
        RETURN;
    END IF;

    SELECT page_id INTO root_id FROM page_translations WHERE locale = 'az' AND slug = ${q(t.rootSlug)};
    IF root_id IS NULL THEN
        RAISE NOTICE 'spec 054: no publications section, tree seed skipped';
        RETURN;
    END IF;
    SELECT path INTO root_path FROM pages WHERE id = root_id;
    SELECT page_id INTO consumer_id FROM page_translations WHERE locale = 'az' AND slug = 'istehlakcilarin-ve-investorlarin-huquqlari';

    FOR g IN
        SELECT * FROM (VALUES
${groupRows}
        ) AS v (sort, slug_az, slug_en, title_az, title_en, intro_az, intro_en, children)
        ORDER BY sort
    LOOP
        -- 1. The group page: found among the root's children by slug (or its "-2" form), created otherwise.
        SELECT p.id, p.path INTO group_id, group_path
        FROM pages p JOIN page_translations t ON t.page_id = p.id AND t.locale = 'az'
        WHERE p.parent_id = root_id AND p.deleted_at IS NULL AND t.slug IN (g.slug_az, g.slug_az || '-2')
        ORDER BY p.id LIMIT 1;

        IF group_id IS NULL THEN
            -- The groups go first in the root's menu: shift the root's children to make room, keeping their order.
            IF created = 0 THEN
                WITH ordered AS (
                    SELECT id, row_number() OVER (ORDER BY sort_order, id) AS rn FROM pages WHERE parent_id = root_id
                )
                UPDATE pages p SET sort_order = (o.rn + 2) * 10 FROM ordered o WHERE p.id = o.id;
            END IF;
            INSERT INTO pages (parent_id, path, sort_order, status)
            VALUES (root_id, root_path, g.sort * 10, 'published')
            RETURNING id INTO group_id;
            group_path := root_path || text2ltree(group_id::text);
            UPDATE pages SET path = group_path WHERE id = group_id;
            -- A slug taken elsewhere in the locale gets "-2", as SlugService would.
            group_slug := CASE WHEN EXISTS (SELECT FROM page_translations WHERE locale = 'az' AND slug = g.slug_az) THEN g.slug_az || '-2' ELSE g.slug_az END;
            INSERT INTO page_translations (page_id, locale, title, slug, content) VALUES (group_id, 'az', g.title_az, group_slug, g.intro_az);
            group_slug := CASE WHEN EXISTS (SELECT FROM page_translations WHERE locale = 'en' AND slug = g.slug_en) THEN g.slug_en || '-2' ELSE g.slug_en END;
            INSERT INTO page_translations (page_id, locale, title, slug, content) VALUES (group_id, 'en', g.title_en, group_slug, g.intro_en);
            created := created + 1;
        END IF;

        -- 2. The group's pages, in the Figma order, while still under the root or the consumer rights section.
        seq := 0;
        FOREACH child_slug IN ARRAY g.children
        LOOP
            seq := seq + 1;
            child_id := NULL;
            SELECT p.id, p.parent_id, p.path INTO child_id, child_parent, child_path
            FROM pages p JOIN page_translations t ON t.page_id = p.id AND t.locale = 'az' AND t.slug = child_slug
            WHERE p.deleted_at IS NULL;
            IF child_id IS NULL OR child_parent = group_id
               OR child_parent IS DISTINCT FROM root_id AND child_parent IS DISTINCT FROM consumer_id THEN
                CONTINUE;
            END IF;

            new_path := group_path || text2ltree(child_id::text);
            UPDATE pages SET parent_id = group_id, path = new_path, sort_order = seq * 10 WHERE id = child_id;
            UPDATE pages SET path = new_path || subpath(path, nlevel(child_path)) WHERE path <@ child_path AND id <> child_id;
            moved := moved + 1;

            -- The consumer section hid these two (0031). In this section one is listed everywhere, the other only in
            -- the dropdown menus (3).
            IF child_parent = consumer_id THEN
                INSERT INTO page_details (page_id, show_in_side_nav) VALUES (child_id, child_slug <> ALL (${array(t.dropdownOnly)}))
                ON CONFLICT (page_id) DO UPDATE SET show_in_side_nav = EXCLUDED.show_in_side_nav;
                IF child_slug = ANY (${array(t.dropdownOnly)}) THEN
                    INSERT INTO page_nav_details (page_id, show_in_dropdown_nav) VALUES (child_id, true)
                    ON CONFLICT (page_id) DO UPDATE SET show_in_dropdown_nav = true;
                END IF;
            END IF;
        END LOOP;
    END LOOP;
    RAISE NOTICE 'spec 054: % group pages created, % pages moved', created, moved;

    -- 4. Legacy pages outside Figma leave every menu; they stay under the root with their addresses.
    INSERT INTO page_details (page_id, show_in_side_nav)
    SELECT t.page_id, false
    FROM page_translations t JOIN pages p ON p.id = t.page_id AND p.parent_id = root_id
    WHERE t.locale = 'az' AND t.slug = ANY (${array(t.hiddenFromMenus)})
    ON CONFLICT (page_id) DO NOTHING;
    GET DIAGNOSTICS changed = ROW_COUNT;
    RAISE NOTICE 'spec 054: % pages left out of the menus', changed;

    -- 5. Menu group labels, where the page has none yet.
    INSERT INTO page_translation_details (page_id, locale, menu_group)
    SELECT az.page_id, v.locale, v.label
    FROM (VALUES
${groupLabelRows}
    ) AS v (az_slug, locale, label)
    JOIN page_translations az ON az.locale = 'az' AND az.slug = v.az_slug
    WHERE EXISTS (SELECT FROM page_translations t WHERE t.page_id = az.page_id AND t.locale = v.locale)
    ON CONFLICT (page_id, locale) DO NOTHING;
    GET DIAGNOSTICS changed = ROW_COUNT;
    RAISE NOTICE 'spec 054: % menu group labels written', changed;

    -- 6a. Figma titles, only over the legacy ones.
    UPDATE page_translations t
    SET title = v.title
    FROM (VALUES
${titleRows}
    ) AS v (az_slug, locale, legacy, title)
    JOIN page_translations az ON az.locale = 'az' AND az.slug = v.az_slug
    WHERE t.page_id = az.page_id AND t.locale = v.locale AND t.title = v.legacy;
    GET DIAGNOSTICS changed = ROW_COUNT;
    RAISE NOTICE 'spec 054: % titles written', changed;

    -- 6b. Figma intros in front of the file link, only over the legacy texts.
    UPDATE page_translations t
    SET content = v.intro || coalesce(t.content, '')
    FROM (VALUES
${introRows}
    ) AS v (az_slug, locale, legacy_md5, intro)
    JOIN page_translations az ON az.locale = 'az' AND az.slug = v.az_slug
    WHERE t.page_id = az.page_id AND t.locale = v.locale AND md5(coalesce(t.content, '')) = v.legacy_md5;
    GET DIAGNOSTICS changed = ROW_COUNT;
    RAISE NOTICE 'spec 054: % intros written', changed;
END
$seed$;
`

writeFileSync(out, sql)
console.log(`written ${out.pathname} (${sql.length} chars)`)
