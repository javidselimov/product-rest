// Spec 054 US6: SQL for running the legacy working papers in by hand (DataGrip), from seed/working-papers.json.
// Writes two files to seed/sql/ (not migrations, nothing runs them automatically):
//   1-check-media.sql            which of the legacy PDFs the environment's media library already holds (read only)
//   2-insert-working-papers.sql  one DO block: inserts the papers, finds each PDF by its legacy file name, skips a paper
//                                whose number + year or legacy page already exists, and reports the counts as NOTICEs
// The PDFs themselves live in object storage, not the database: SQL can only link a file already uploaded.
//
//   node specs/054-publications-research/seed/build-papers-sql.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const outDir = path.join(here, 'sql')
const { papers, source } = JSON.parse(fs.readFileSync(path.join(here, 'working-papers.json'), 'utf8'))
const TAG = '$wp$'
const JEL = /^[A-Z][0-9]{1,2}$/

const all = JSON.stringify(papers)
if (all.includes(TAG)) throw new Error(`the data contains ${TAG}`)
const str = (s) => (s == null || s === '' ? 'NULL' : `${TAG}${s}${TAG}`)
const arr = (items) => (items.length ? `ARRAY[${items.map(str).join(', ')}]::text[]` : `'{}'::text[]`)
const fileName = (t) => (t?.files[0] ? path.basename(new URL(t.files[0].url).pathname) : null)
const code = (p) => `${String(p.number).padStart(2, '0')}-${p.year}`

const names = [...new Set(papers.flatMap((p) => Object.values(p.translations).map(fileName)).filter(Boolean))]
const header = `-- Generated by specs/054-publications-research/seed/build-papers-sql.mjs from ${source}. Do not edit by hand.\n`

const check = `${header}-- Read only. How many of the ${names.length} legacy PDFs are in the media library, and which are missing.
WITH legacy(name) AS (VALUES
${names.map((n) => `    (${str(n)})`).join(',\n')}
)
SELECT count(m.id) AS found, count(*) - count(m.id) AS missing, count(*) AS total
FROM legacy l
LEFT JOIN LATERAL (SELECT id FROM media_assets WHERE original_name = l.name AND deleted_at IS NULL ORDER BY id LIMIT 1) m ON true;

-- The missing ones:
WITH legacy(name) AS (VALUES
${names.map((n) => `    (${str(n)})`).join(',\n')}
)
SELECT l.name FROM legacy l
WHERE NOT EXISTS (SELECT FROM media_assets WHERE original_name = l.name AND deleted_at IS NULL);
`

const rows = papers
  .map((p) => {
    const tr = Object.entries(p.translations)
      .map(([locale, t]) => `        PERFORM pg_temp.wp_translation(pid, '${locale}', ${str(t.title)}, ${arr(t.authors)}, ${str(t.abstract)}, ${arr(t.keywords)}, ${str(fileName(t))});`)
      .join('\n')
    return `    -- ${code(p)}, page-${p.legacyPageId}
    IF NOT EXISTS (SELECT FROM working_papers WHERE deleted_at IS NULL AND ((number = ${p.number} AND year = ${p.year}) OR legacy_page_id = ${p.legacyPageId})) THEN
        INSERT INTO working_papers (number, year, paper_language, jel_codes, legacy_page_id, status)
        VALUES (${p.number}, ${p.year}, '${p.paperLanguage ?? 'other'}', ${arr(p.jelCodes.filter((c) => JEL.test(c)))}, ${p.legacyPageId}, 'published')
        RETURNING id INTO pid;
${tr}
        created := created + 1;
    ELSE
        skipped := skipped + 1;
    END IF;`
  })
  .join('\n')

const insert = `${header}-- ${papers.length} legacy working papers (az + en). Run 1-check-media.sql first: a PDF missing from the media library
-- leaves that locale without a file (media_id NULL). Safe to run again: a paper whose number + year or legacy page
-- already exists is skipped, so one an editor entered by hand stays as it is. Atomic: an error inserts nothing.

-- Session-local helper (pg_temp): one translation, its PDF found by the legacy file name.
CREATE OR REPLACE FUNCTION pg_temp.wp_translation(pid integer, loc text, t text, a text[], ab text, k text[], file text)
RETURNS void LANGUAGE plpgsql AS $fn$
DECLARE
    mid bigint;
BEGIN
    SELECT id INTO mid FROM media_assets WHERE original_name = file AND deleted_at IS NULL ORDER BY id LIMIT 1;
    IF mid IS NULL THEN
        RAISE NOTICE 'paper %: % PDF % is not in the media library', pid, loc, file;
    END IF;
    INSERT INTO working_paper_translations (paper_id, locale, title, authors, abstract, keywords, media_id)
    VALUES (pid, loc, t, a, ab, k, mid);
END $fn$;

DO $$
DECLARE
    pid integer;
    created integer := 0;
    skipped integer := 0;
BEGIN
${rows}
    RAISE NOTICE 'working papers: created %, skipped (already there) %', created, skipped;
END $$;
`

fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(path.join(outDir, '1-check-media.sql'), check)
fs.writeFileSync(path.join(outDir, '2-insert-working-papers.sql'), insert)
console.log(`${papers.length} papers, ${names.length} PDF names → ${path.relative(process.cwd(), outDir)}`)
